CREATE SCHEMA knowledge_desk;
REVOKE ALL ON SCHEMA knowledge_desk FROM PUBLIC, anon, authenticated;
CREATE ROLE knowledge_desk_runtime NOLOGIN;
GRANT USAGE ON SCHEMA knowledge_desk TO knowledge_desk_runtime;

CREATE TABLE knowledge_desk.members (
    user_id text PRIMARY KEY,
    role text NOT NULL CHECK (role IN ('reader', 'editor', 'operator'))
);

CREATE TABLE knowledge_desk.documents (
    id text PRIMARY KEY,
    title text NOT NULL,
    text text NOT NULL,
    source text NOT NULL,
    sort_order bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE knowledge_desk.document_access (
    document_id text PRIMARY KEY REFERENCES knowledge_desk.documents(id) ON DELETE CASCADE,
    owner_id text NOT NULL REFERENCES knowledge_desk.members(user_id),
    shared smallint NOT NULL DEFAULT 0 CHECK (shared IN (0, 1))
);
CREATE INDEX document_access_owner ON knowledge_desk.document_access(owner_id);

CREATE TABLE knowledge_desk.document_pdfs (
    document_id text PRIMARY KEY REFERENCES knowledge_desk.documents(id) ON DELETE CASCADE,
    filename text NOT NULL,
    content bytea NOT NULL,
    text_hash text NOT NULL,
    page_spans text NOT NULL
);

CREATE TABLE knowledge_desk.document_uploads (
    document_id text PRIMARY KEY REFERENCES knowledge_desk.documents(id) ON DELETE CASCADE,
    version_date text NOT NULL,
    index_key text NOT NULL UNIQUE
);

CREATE TABLE knowledge_desk.hidden_manifest_sources (
    collection text NOT NULL,
    source text NOT NULL,
    PRIMARY KEY (collection, source)
);

CREATE TABLE knowledge_desk.requests (
    id text PRIMARY KEY,
    name text NOT NULL,
    question text NOT NULL,
    status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'in_progress', 'resolved')),
    document_id text REFERENCES knowledge_desk.documents(id) ON DELETE SET NULL,
    created_at text,
    user_id text NOT NULL REFERENCES knowledge_desk.members(user_id)
);
CREATE INDEX requests_owner_date ON knowledge_desk.requests(user_id, created_at DESC);
CREATE INDEX requests_document ON knowledge_desk.requests(document_id);

CREATE TABLE knowledge_desk.request_replies (
    id text PRIMARY KEY,
    request_id text NOT NULL REFERENCES knowledge_desk.requests(id) ON DELETE CASCADE,
    text text NOT NULL,
    created_at text NOT NULL,
    edited_at text,
    deleted smallint NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    sort_order bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX request_replies_request ON knowledge_desk.request_replies(request_id);

CREATE TABLE knowledge_desk.consultation_drafts (
    draft_id text PRIMARY KEY,
    user_id text NOT NULL REFERENCES knowledge_desk.members(user_id),
    version integer NOT NULL CHECK (version > 0),
    name text NOT NULL,
    question text NOT NULL,
    status text NOT NULL CHECK (status IN ('draft', 'awaiting_confirmation', 'submitted', 'failed', 'cancelled')),
    stop_code text,
    request_id text REFERENCES knowledge_desk.requests(id)
);
CREATE INDEX consultation_drafts_owner ON knowledge_desk.consultation_drafts(user_id);
CREATE INDEX consultation_drafts_request ON knowledge_desk.consultation_drafts(request_id);

CREATE TABLE knowledge_desk.consultation_receipts (
    user_id text NOT NULL REFERENCES knowledge_desk.members(user_id),
    operation_key text NOT NULL,
    payload_hash text NOT NULL,
    request_id text NOT NULL REFERENCES knowledge_desk.requests(id),
    PRIMARY KEY (user_id, operation_key)
);
CREATE INDEX consultation_receipts_request ON knowledge_desk.consultation_receipts(request_id);

CREATE TABLE knowledge_desk.integration_events (
    event_id text PRIMARY KEY,
    request_id text NOT NULL UNIQUE REFERENCES knowledge_desk.requests(id),
    user_id text NOT NULL REFERENCES knowledge_desk.members(user_id),
    type text NOT NULL CHECK (type = 'request.created'),
    status text NOT NULL CHECK (status IN ('pending', 'delivered', 'failed', 'unknown')),
    reason text,
    receipt text,
    updated_at text NOT NULL,
    receiver_key text,
    attempt_until double precision
);
CREATE INDEX integration_events_owner ON knowledge_desk.integration_events(user_id);

CREATE TABLE knowledge_desk.n8n_receipts (
    event_id uuid PRIMARY KEY,
    request_id uuid NOT NULL,
    execution_id text NOT NULL CHECK (execution_id ~ '^[0-9]{1,64}$')
);

GRANT SELECT ON knowledge_desk.members TO knowledge_desk_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON knowledge_desk.documents, knowledge_desk.document_access,
    knowledge_desk.document_pdfs, knowledge_desk.document_uploads, knowledge_desk.hidden_manifest_sources,
    knowledge_desk.requests, knowledge_desk.request_replies, knowledge_desk.consultation_drafts,
    knowledge_desk.consultation_receipts, knowledge_desk.integration_events TO knowledge_desk_runtime;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA knowledge_desk TO knowledge_desk_runtime;
